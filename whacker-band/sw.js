self.addEventListener('install',e=>{
  e.waitUntil(caches.open(VERSION).then(c=>Promise.all(DATEIEN.map(u=>c.add(u).catch(()=>{})))).then(()=>self.skipWaiting()));
});
self.addEventListener('activate',e=>{
  e.waitUntil(caches.keys().then(k=>Promise.all(k.filter(n=>n.startsWith('sw-band-')&&n!==VERSION).map(n=>caches.delete(n)))).then(()=>self.clients.claim()));
});
self.addEventListener('fetch',e=>{
  const r=e.request, u=new URL(r.url);
  if(r.method!=='GET'||u.origin!==location.origin) return;           // z. B. Zähler: normal übers Netz
  const frisch=r.mode==='navigate'||/\.(html|js|webmanifest)$/.test(u.pathname)||u.pathname.endsWith('/');
  if(frisch){                                                        // erst Internet (neueste Fassung), sonst Speicher
    e.respondWith(fetch(r).then(a=>{ if(a.ok){ const k=a.clone(); caches.open(VERSION).then(c=>c.put(r,k)); } return a; })
      .catch(()=>caches.match(r).then(t=>t||caches.match(r,{ignoreSearch:true})).then(t=>t||caches.match('index.html'))));
  } else {                                                            // Klänge, Bilder: erst Speicher
    e.respondWith(caches.match(r).then(t=>t||fetch(r).then(a=>{ if(a.ok){ const k=a.clone(); caches.open(VERSION).then(c=>c.put(r,k)); } return a; })));
  }
});
